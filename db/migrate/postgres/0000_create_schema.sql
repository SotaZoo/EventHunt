CREATE TABLE IF NOT EXISTS events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL,
    url TEXT NOT NULL UNIQUE,
    title TEXT NOT NULL,
    start_at TIMESTAMPTZ,
    ends_at TIMESTAMPTZ,
    venue TEXT,
    neighborhood TEXT,
    description TEXT,
    host TEXT,
    first_seen TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fit_input_hash TEXT,
    fit_score DOUBLE PRECISION CHECK (fit_score IS NULL OR (fit_score BETWEEN 0.0 AND 1.0)),
    fit_reasoning TEXT,
    urgency TEXT CHECK (urgency IS NULL OR urgency IN ('low', 'medium', 'high')),
    urgency_reason TEXT,
    scoring_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (scoring_status IN ('pending', 'scored', 'failed', 'skipped')),
    scoring_failed_reason TEXT,
    prompt_version TEXT,
    taste_sha TEXT,
    posted_at TIMESTAMPTZ,
    posting_claimed_at TIMESTAMPTZ,
    posting_claim_token TEXT
);

CREATE INDEX IF NOT EXISTS idx_events_posted_at ON events(posted_at);
CREATE INDEX IF NOT EXISTS idx_events_scoring_status ON events(scoring_status);
CREATE INDEX IF NOT EXISTS idx_events_start_at ON events(start_at);
CREATE INDEX IF NOT EXISTS idx_events_fit_score ON events(fit_score);
CREATE INDEX IF NOT EXISTS idx_events_posting_claim ON events(posting_claimed_at);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE CHECK (char_length(email) > 0 AND char_length(email) <= 254),
    display_name TEXT NOT NULL CHECK (char_length(display_name) > 0 AND char_length(display_name) <= 80),
    invite_code_hash TEXT UNIQUE CHECK (invite_code_hash IS NULL OR char_length(invite_code_hash) = 64),
    interest_flags_json TEXT NOT NULL DEFAULT '{}',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_users_invite_code_hash ON users(invite_code_hash);
CREATE INDEX IF NOT EXISTS idx_users_is_active ON users(is_active);

CREATE TABLE IF NOT EXISTS user_event_states (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'new'
        CHECK (status IN (
            'new',
            'saved',
            'dismissed',
            'interested',
            'registering',
            'applied',
            'pending_approval',
            'confirmed',
            'rejected'
        )),
    rating INTEGER CHECK (rating IS NULL OR rating IN (-1, 0, 1)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status_updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    rating_updated_at TIMESTAMPTZ,
    PRIMARY KEY (user_id, event_id)
);

CREATE INDEX IF NOT EXISTS idx_user_event_states_event ON user_event_states(event_id);
CREATE INDEX IF NOT EXISTS idx_user_event_states_status ON user_event_states(status);
CREATE INDEX IF NOT EXISTS idx_user_event_states_rating ON user_event_states(rating);

CREATE TABLE IF NOT EXISTS linked_identities (
    provider TEXT NOT NULL CHECK (char_length(provider) > 0 AND char_length(provider) <= 32),
    subject TEXT NOT NULL CHECK (char_length(subject) > 0 AND char_length(subject) <= 255),
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    email TEXT NOT NULL CHECK (char_length(email) > 0 AND char_length(email) <= 254),
    email_verified BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (provider, subject)
);

CREATE INDEX IF NOT EXISTS idx_linked_identities_user ON linked_identities(user_id);
CREATE INDEX IF NOT EXISTS idx_linked_identities_email ON linked_identities(email);

CREATE TABLE IF NOT EXISTS alpha_invites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL CHECK (char_length(email) > 0 AND char_length(email) <= 254),
    normalized_email TEXT NOT NULL CHECK (char_length(normalized_email) > 0 AND char_length(normalized_email) <= 254),
    invited_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    accepted_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    accepted_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_alpha_invites_active_email
    ON alpha_invites(normalized_email)
    WHERE revoked_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_alpha_invites_accepted_user
    ON alpha_invites(accepted_user_id);

CREATE TABLE IF NOT EXISTS runtime_markers (
    name TEXT PRIMARY KEY,
    reason TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS cycle_health (
    id BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (id),
    consecutive_all_failed INTEGER NOT NULL DEFAULT 0 CHECK (consecutive_all_failed >= 0),
    last_error TEXT,
    last_failed_at TIMESTAMPTZ,
    last_success_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS cycle_locks (
    name TEXT PRIMARY KEY,
    owner TEXT NOT NULL,
    locked_until TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
